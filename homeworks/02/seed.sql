-- =====================================================================
--  ЧАСТЬ 2. Сгенерированные данные
--
--  200 дополнительных заказов за последние полтора года.
--  setseed фиксирует генератор случайных чисел: у всей группы
--  получатся одинаковые данные, а значит — одинаковые ответы в отчётах.
-- =====================================================================

SELECT setseed(0.42);

-- Заказы: случайный существующий адрес, случайный статус, случайная дата
INSERT INTO orders (customer_id, address_id, status, created_at)
SELECT a.customer_id,
       a.id,
       (ARRAY['new','paid','shipped','delivered','delivered','delivered','cancelled'])
           [1 + floor(random() * 7)::int],
       now() - (random() * 540)::int * interval '1 day'
             - (random() * 86400)::int * interval '1 second'
FROM generate_series(1, 200) AS g
CROSS JOIN LATERAL (
    SELECT id, customer_id FROM address ORDER BY random() LIMIT 1
) AS a;

-- Позиции: 1-3 случайных товара с ценой, отличающейся от текущей на ±10 %
WITH price_list AS (
    SELECT product_id, price FROM pc      WHERE price IS NOT NULL
    UNION ALL
    SELECT product_id, price FROM laptop  WHERE price IS NOT NULL
    UNION ALL
    SELECT product_id, price FROM printer
)
INSERT INTO order_item (order_id, product_id, quantity, price)
SELECT o.id,
       pl.product_id,
       1 + floor(random() * 2)::int,
       --round(pl.price * (0.9 + random() * 0.2), 2)
       round((pl.price * (0.9 + random() * 0.2))::numeric, 2)
FROM orders o
CROSS JOIN LATERAL (
    SELECT product_id, price
    FROM price_list
    ORDER BY random()
    LIMIT 1 + floor(random() * 3)::int
) AS pl
WHERE o.id > 16;          -- только сгенерированные заказы

COMMIT;


